# --- Build CHR ROM ---
def build_chr():
    tiles = bytearray()

    # Pattern Table 0 (Background): 256 tiles
    # $00: blank
    tiles += BLANK  # 0

    # $01-$1A: A-Z
    for ch in 'ABCDEFGHIJKLMNOPQRSTUVWXYZ':
        tiles += make_tile(font_data[ch])

    # $1B-$24: 0-9
    for ch in '0123456789':
        tiles += make_tile(number_data[ch])

    # $25: colon, $26: !, $27: -, $28: >, $29: ., $2A: ?
    tiles += colon_tile   # $25
    tiles += excl_tile    # $26
    tiles += dash_tile    # $27
    tiles += arrow_tile   # $28
    tiles += period_tile  # $29
    tiles += question_tile # $2A

    # $2B-$2F: padding
    for _ in range(5):
        tiles += BLANK

    # $30-$35: Katakana
    tiles += gu_tile      # $30
    tiles += chouon_tile  # $31
    tiles += chi_tile     # $32
    tiles += syo_tile     # $33
    tiles += ki_tile      # $34
    tiles += pa_tile      # $35

    # $36-$3F: padding
    for _ in range(10):
        tiles += BLANK

    # $40-$43: Rock hand (2x2)
    tiles += rock_tl      # $40
    tiles += rock_tr      # $41
    tiles += rock_bl      # $42
    tiles += rock_br      # $43

    # $44-$47: Scissors hand (2x2)
    tiles += scis_tl      # $44
    tiles += scis_tr      # $45
    tiles += scis_bl      # $46
    tiles += scis_br      # $47

    # $48-$4B: Paper hand (2x2)
    tiles += paper_tl     # $48
    tiles += paper_tr     # $49
    tiles += paper_bl     # $4A
    tiles += paper_br     # $4B

    # $4C-$4F: padding
    for _ in range(4):
        tiles += BLANK

    # $50-$59: decorative tiles
    tiles += hline_top    # $50
    tiles += hline_bot    # $51
    tiles += vline_l      # $52
    tiles += vline_r      # $53
    tiles += corner_tl    # $54
    tiles += corner_tr    # $55
    tiles += corner_bl    # $56
    tiles += corner_br    # $57
    tiles += star_tile    # $58
    tiles += vs_tile      # $59

    # $5A-$5F: padding to reach $60
    current_count = len(tiles) // 16
    for _ in range(0x60 - current_count):
        tiles += BLANK

    # $60-$62: Player top row (shared)
    for t in player_top:
        tiles += t
    # $63-$65: Player happy eyes
    for t in player_happy_eyes:
        tiles += t
    # $66-$68: Player happy mouth
    for t in player_happy_mouth:
        tiles += t
    # $69-$6B: Player sad eyes
    for t in player_sad_eyes:
        tiles += t
    # $6C-$6E: Player sad mouth
    for t in player_sad_mouth:
        tiles += t
    # $6F-$71: padding
    for _ in range(3):
        tiles += BLANK
    # $72-$74: CPU top row (shared)
    for t in cpu_top:
        tiles += t
    # $75-$77: CPU happy eyes
    for t in cpu_happy_eyes:
        tiles += t
    # $78-$7A: CPU happy mouth
    for t in cpu_happy_mouth:
        tiles += t
    # $7B-$7D: CPU sad eyes
    for t in cpu_sad_eyes:
        tiles += t
    # $7E-$80: CPU sad mouth
    for t in cpu_sad_mouth:
        tiles += t

    # Pad rest of pattern table 0 to 256 tiles
    current_count = len(tiles) // 16
    for _ in range(256 - current_count):
        tiles += BLANK

    # Pattern Table 1 (Sprites): 256 tiles - all blank for now
    # (We use background tiles only for this game)
    for _ in range(256):
        tiles += BLANK

    assert len(tiles) == 8192, f"CHR ROM should be 8192 bytes, got {len(tiles)}"
    return bytes(tiles)


if __name__ == '__main__':
    chr_data = build_chr()
    with open('chr.bin', 'wb') as f:
        f.write(chr_data)
    print(f"Generated chr.bin ({len(chr_data)} bytes)")
